-- Full schema. Dropped and recreated by scripts/reset-db.js on every reset.
--
-- Delete semantics (documented decision, exercised by e2e test 3):
-- Removing a Leader CASCADE-deletes everything owned by that Leader:
--   users(leader)  -> teams.leader_id CASCADE
--   teams          -> users.team_id CASCADE (the team's Members)
--                  -> invitations.team_id CASCADE (pending + accepted invites)
--   users(member)  -> onboarding_progress.user_id CASCADE
-- Nothing is kept behind as an orphan.

DROP TABLE IF EXISTS onboarding_progress CASCADE;
DROP TABLE IF EXISTS invitations CASCADE;
DROP TABLE IF EXISTS teams CASCADE;
DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE users (
  id            integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  email         text        NOT NULL UNIQUE,
  password_hash text        NOT NULL,
  role          text        NOT NULL CHECK (role IN ('superadmin', 'leader', 'member')),
  team_id       integer,
  created_at    timestamptz NOT NULL
);

CREATE TABLE teams (
  id         integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name       text        NOT NULL,
  -- One team per Leader (MVP constraint).
  leader_id  integer     NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL
);

ALTER TABLE users
  ADD CONSTRAINT users_team_id_fkey
  FOREIGN KEY (team_id) REFERENCES teams (id) ON DELETE CASCADE;

CREATE TABLE invitations (
  id          integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  email       text        NOT NULL,
  token       text        NOT NULL UNIQUE,
  team_id     integer     NOT NULL REFERENCES teams (id) ON DELETE CASCADE,
  status      text        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted')),
  created_at  timestamptz NOT NULL,
  accepted_at timestamptz
);

CREATE TABLE onboarding_progress (
  id           integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id      integer     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  step_key     text        NOT NULL,
  completed_at timestamptz NOT NULL,
  -- Guarantees "exactly three progress rows, no duplicates" for a finished Member.
  UNIQUE (user_id, step_key)
);
