// Deterministic seeds. Every seed uses explicit ids, fixed passwords and the
// fixed clock, so the same scenario always produces a byte-identical dump.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { query } from './db.js';
import { now } from './clock.js';
import { hashPassword } from './auth.js';
import { inviteToken } from './invitations.js';
import { clearEmails } from './email.js';

const SCHEMA_SQL = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  'schema.sql',
);

export const CREDENTIALS = {
  superadmin: { email: 'admin@onboard.test', password: 'superadmin-pass' },
  leaderA: { email: 'leader-a@onboard.test', password: 'leader-a-pass' },
  leaderB: { email: 'leader-b@onboard.test', password: 'leader-b-pass' },
  memberOne: { email: 'member-one@onboard.test', password: 'member-one-pass' },
  memberTwo: { email: 'member-two@onboard.test', password: 'member-two-pass' },
  memberThree: { email: 'member-three@onboard.test', password: 'member-three-pass' },
};

export const INVITED = {
  first: 'invited-one@onboard.test',
  second: 'invited-two@onboard.test',
};

async function createSchema() {
  await query(fs.readFileSync(SCHEMA_SQL, 'utf8'));
}

async function insertUser({ id, email, password, role, teamId = null }) {
  await query(
    `INSERT INTO users (id, email, password_hash, role, team_id, created_at)
     VALUES ($1, $2, $3, $4, $5, $6)`,
    [id, email, hashPassword(email, password), role, teamId, now()],
  );
}

async function insertTeam({ id, name, leaderId }) {
  await query('INSERT INTO teams (id, name, leader_id, created_at) VALUES ($1, $2, $3, $4)', [
    id,
    name,
    leaderId,
    now(),
  ]);
}

async function insertInvitation({ id, email, teamId, status = 'pending', nth = 0 }) {
  await query(
    `INSERT INTO invitations (id, email, token, team_id, status, created_at, accepted_at)
     VALUES ($1, $2, $3, $4, $5, $6, $7)`,
    [
      id,
      email,
      inviteToken(teamId, email, nth),
      teamId,
      status,
      now(),
      status === 'accepted' ? now() : null,
    ],
  );
}

async function insertProgress({ id, userId, stepKey }) {
  await query(
    'INSERT INTO onboarding_progress (id, user_id, step_key, completed_at) VALUES ($1, $2, $3, $4)',
    [id, userId, stepKey, now()],
  );
}

// Identity columns are `GENERATED BY DEFAULT`, so explicit ids above do not move
// the sequences. Realign them or the app's own inserts collide with seeded ids.
async function realignSequences() {
  for (const table of ['users', 'teams', 'invitations', 'onboarding_progress']) {
    await query(
      `SELECT setval(pg_get_serial_sequence('${table}', 'id'),
                     coalesce((SELECT max(id) FROM ${table}), 0) + 1, false)`,
    );
  }
}

async function seedSuperadmin() {
  await insertUser({ id: 1, ...CREDENTIALS.superadmin, role: 'superadmin' });
}

const SEEDS = {
  /** Production-like starting point: empty except for the Superadmin. */
  async base() {
    await seedSuperadmin();
  },

  /** Test 2: one Superadmin and one Leader (with an empty team). */
  async 'superadmin-and-leader'() {
    await seedSuperadmin();
    await insertUser({ id: 2, ...CREDENTIALS.leaderA, role: 'leader' });
    await insertTeam({ id: 1, name: `${CREDENTIALS.leaderA.email}'s team`, leaderId: 2 });
  },

  /**
   * Test 3: one Superadmin and two Leaders, where Leader A has a team with one
   * Member who has completed one checkbox.
   */
  async 'two-leaders-one-with-member'() {
    await seedSuperadmin();
    await insertUser({ id: 2, ...CREDENTIALS.leaderA, role: 'leader' });
    await insertUser({ id: 3, ...CREDENTIALS.leaderB, role: 'leader' });
    await insertTeam({ id: 1, name: `${CREDENTIALS.leaderA.email}'s team`, leaderId: 2 });
    await insertTeam({ id: 2, name: `${CREDENTIALS.leaderB.email}'s team`, leaderId: 3 });
    await insertUser({ id: 4, ...CREDENTIALS.memberOne, role: 'member', teamId: 1 });
    await insertInvitation({
      id: 1,
      email: CREDENTIALS.memberOne.email,
      teamId: 1,
      status: 'accepted',
    });
    await insertProgress({ id: 1, userId: 4, stepKey: 'read_handbook' });
  },

  /** Test 4: a Member who has checked two of the three boxes. */
  async 'member-two-of-three'() {
    await seedSuperadmin();
    await insertUser({ id: 2, ...CREDENTIALS.leaderA, role: 'leader' });
    await insertTeam({ id: 1, name: `${CREDENTIALS.leaderA.email}'s team`, leaderId: 2 });
    await insertUser({ id: 3, ...CREDENTIALS.memberOne, role: 'member', teamId: 1 });
    await insertInvitation({
      id: 1,
      email: CREDENTIALS.memberOne.email,
      teamId: 1,
      status: 'accepted',
    });
    await insertProgress({ id: 1, userId: 3, stepKey: 'read_handbook' });
    await insertProgress({ id: 2, userId: 3, stepKey: 'setup_accounts' });
  },

  /**
   * Cascade-depth fixture: two Leaders, where Leader A's team holds three
   * Members with different amounts of progress (none / one step / all three).
   */
  async 'leader-with-three-members'() {
    await seedSuperadmin();
    await insertUser({ id: 2, ...CREDENTIALS.leaderA, role: 'leader' });
    await insertUser({ id: 3, ...CREDENTIALS.leaderB, role: 'leader' });
    await insertTeam({ id: 1, name: `${CREDENTIALS.leaderA.email}'s team`, leaderId: 2 });
    await insertTeam({ id: 2, name: `${CREDENTIALS.leaderB.email}'s team`, leaderId: 3 });

    const members = [CREDENTIALS.memberOne, CREDENTIALS.memberTwo, CREDENTIALS.memberThree];
    for (const [index, member] of members.entries()) {
      const id = 4 + index;
      await insertUser({ id, ...member, role: 'member', teamId: 1 });
      await insertInvitation({ id: index + 1, email: member.email, teamId: 1, status: 'accepted' });
    }

    // memberOne: nothing. memberTwo: one step. memberThree: all three.
    await insertProgress({ id: 1, userId: 5, stepKey: 'read_handbook' });
    await insertProgress({ id: 2, userId: 6, stepKey: 'read_handbook' });
    await insertProgress({ id: 3, userId: 6, stepKey: 'setup_accounts' });
    await insertProgress({ id: 4, userId: 6, stepKey: 'meet_team' });
  },

  /** Test 5: one Superadmin, one Leader and one pending invitation. */
  async 'pending-invitation'() {
    await seedSuperadmin();
    await insertUser({ id: 2, ...CREDENTIALS.leaderA, role: 'leader' });
    await insertTeam({ id: 1, name: `${CREDENTIALS.leaderA.email}'s team`, leaderId: 2 });
    await insertInvitation({ id: 1, email: INVITED.first, teamId: 1 });
  },
};

export const SEED_NAMES = Object.keys(SEEDS);

/** The token of the invitation created by the `pending-invitation` seed. */
export const PENDING_INVITE_TOKEN = inviteToken(1, INVITED.first, 0);

export async function resetDatabase(seedName = 'base') {
  const seed = SEEDS[seedName];
  if (!seed) throw new Error(`Unknown seed "${seedName}". Known: ${SEED_NAMES.join(', ')}`);
  await createSchema();
  await seed();
  await realignSequences();
  clearEmails();
  return seedName;
}
